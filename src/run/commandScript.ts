// Generates the job's meta/command.sh from a profile.
//
// Profiles declare argv arrays, never shell strings. This file turns them into
// a short bash script where every argument is a quoted word, so a value with
// spaces, quotes, $ or ; is passed through exactly. The script is uploaded
// with the source and kept in the job's evidence, so what ran is inspectable.
//
// Order of environment: profile env first, then the machine's private env, so
// a machine-specific value (for example an installed tool path on that Mac)
// can't be silently overridden by a generic manifest. PATH gets the profile's
// pathPrepend before the machine's. Placeholders @JOB_DIR@, @SRC_DIR@ and
// @CACHE_DIR@ become references to variables the supervisor exports.

import { usageError } from '../errors.ts';
import type { Machine } from '../schema/machines.ts';
import type { Profile } from '../schema/manifest.ts';
import { remotePathWord, shellQuote } from '../transport/shellQuote.ts';

const PLACEHOLDER_VARIABLES: Readonly<Record<string, string>> = {
  '@JOB_DIR@': 'FLEET_RUNNER_JOB_DIR',
  '@SRC_DIR@': 'FLEET_RUNNER_SRC_DIR',
  '@CACHE_DIR@': 'FLEET_RUNNER_CACHE_DIR',
};

/** One shell word for a value, expanding the runner placeholders to variable references. */
export function renderWord(value: string, profile: Profile): string {
  const parts = value.split(/(@JOB_DIR@|@SRC_DIR@|@CACHE_DIR@)/);
  const words = parts
    .filter((part) => part !== '')
    .map((part) => {
      const variable = PLACEHOLDER_VARIABLES[part];
      if (variable === undefined) return shellQuote(part);
      if (part === '@CACHE_DIR@' && profile.cache === undefined) {
        throw usageError(`Profile ${profile.name} uses @CACHE_DIR@ but declares no cache.`);
      }
      return `"$${variable}"`;
    });
  return words.length === 0 ? "''" : words.join('');
}

export function renderCommandScript(input: {
  readonly profile: Profile;
  readonly machine: Machine;
  readonly extraArgs: readonly string[];
  readonly jobId: string;
  readonly label: string;
}): string {
  const { profile, machine, extraArgs } = input;
  if (extraArgs.length > 0 && !profile.allowExtraArgs) {
    throw usageError(`Profile ${profile.name} doesn't accept extra arguments.`);
  }
  for (const name of profile.requires.machineEnv) {
    if (machine.env[name] === undefined) {
      throw usageError(`Profile ${profile.name} needs ${name} in machine ${machine.id}'s env (machines.json).`);
    }
  }
  const lines: string[] = [
    `# Generated by fleet-runner for job ${input.jobId} (${input.label}).`,
    '# Runs from the job src folder; each argument is one quoted word.',
    'set -e',
  ];
  const pathEntries = [...profile.pathPrepend, ...machine.pathPrepend];
  if (pathEntries.length > 0) {
    lines.push(`export PATH=${pathEntries.map(remotePathWord).join("':'")}':'"$PATH"`);
  }
  for (const [name, value] of Object.entries(profile.env)) lines.push(`export ${name}=${renderWord(value, profile)}`);
  for (const [name, value] of Object.entries(machine.env)) lines.push(`export ${name}=${renderWord(value, profile)}`);
  for (const tool of profile.requires.tools) {
    lines.push(`command -v ${shellQuote(tool)} >/dev/null 2>&1 || { printf '%s\\n' ${shellQuote(`fleet-runner: ${tool} is not on PATH`)} >&2; exit 127; }`);
  }
  if (profile.cwd !== '.') lines.push(`cd -- "$FLEET_RUNNER_SRC_DIR"/${shellQuote(profile.cwd)}`);
  for (const step of profile.prepare) lines.push(step.map((word) => renderWord(word, profile)).join(' '));
  lines.push(`exec ${[...profile.argv, ...extraArgs].map((word) => renderWord(word, profile)).join(' ')}`);
  return `${lines.join('\n')}\n`;
}
